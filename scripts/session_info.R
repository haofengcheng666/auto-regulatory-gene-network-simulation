# dump sessionInfo() and a few other bits of machine state to
# docs/sessionInfo.txt so the appendix reproducibility table can cite
# something concrete.  run from benchmark/ folder.

dir.create("docs", showWarnings = FALSE, recursive = TRUE)
out <- "docs/sessionInfo.txt"

sink(out)
cat("# generated by scripts/session_info.R on",
    format(Sys.time(), "%Y-%m-%d %H:%M:%S %Z"), "\n")
cat("# cwd:", getwd(), "\n")
cat("# nodename:", Sys.info()[["nodename"]], "\n")
cat("# user:", Sys.info()[["user"]], "\n\n")
print(sessionInfo())
sink()

cat("wrote", out, "\n")
